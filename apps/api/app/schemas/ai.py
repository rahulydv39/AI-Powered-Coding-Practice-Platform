"""Pydantic schemas for AI Assistant requests and responses."""

from typing import List, Optional
from pydantic import BaseModel, Field


class AiExplainRequest(BaseModel):
    """Payload for code explanation requests."""

    code: str = Field(
        ...,
        min_length=1,
        max_length=20000,
        description="Current Python code from student editor",
    )
    question: Optional[str] = Field(
        default=None,
        max_length=500,
        description="Optional student question regarding the code",
    )
    provider: Optional[str] = Field(
        default=None,
        description="Target AI provider (gemini, claude, openai). Defaults to system default.",
    )


class AiHintRequest(BaseModel):
    """Payload for progressive debugging hint requests."""

    code: str = Field(
        ...,
        min_length=1,
        max_length=20000,
        description="Current Python code from student editor",
    )
    question: Optional[str] = Field(
        default=None,
        max_length=500,
        description="Optional student question regarding the code",
    )
    hint_level: int = Field(
        default=1,
        ge=1,
        le=5,
        description="Progressive hint level (1: Concept, 2: Specific Condition, 3: Concrete Direction)",
    )
    provider: Optional[str] = Field(
        default=None,
        description="Target AI provider (gemini, claude, openai). Defaults to system default.",
    )


class AiResponseSchema(BaseModel):
    """Standardized response from AI Assistant endpoints."""

    success: bool = Field(..., description="Whether generation succeeded")
    mode: str = Field(..., description="Action mode: 'explain' or 'hint'")
    content: str = Field(..., description="Markdown response generated by AI")
    model: str = Field(..., description="Model identifier used")
    provider: str = Field(default="gemini", description="Provider identifier used (gemini, claude, openai)")
    hint_level: Optional[int] = Field(
        default=None, description="Progressive hint step if mode is 'hint'"
    )
    error_message: Optional[str] = Field(
        default=None, description="Human-readable error details if generation failed"
    )


class ProviderInfoSchema(BaseModel):
    """Metadata describing a supported AI provider."""

    id: str = Field(..., description="Provider unique identifier (gemini, claude, openai)")
    name: str = Field(..., description="Human-friendly provider name")
    model: str = Field(..., description="Configured model identifier")
    configured: bool = Field(..., description="Whether API credentials are present")


class ProvidersListResponse(BaseModel):
    """Available AI providers and system default configuration."""

    default_provider: str = Field(..., description="System-level default AI provider")
    providers: List[ProviderInfoSchema] = Field(..., description="List of supported AI providers")
